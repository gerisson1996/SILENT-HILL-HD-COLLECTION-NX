#!/usr/bin/env python3
"""
Finds the "this" adjusting thunks (multiple inheritance) the analysis left inside other functions.

MSVC/XDK emits them as two instructions, back to back, often in runs:

    addi r3, r3, -N
    b    <method>

They are only reached through vtables, so the codegen's analysis does not see them as function starts and
folds a run of them, plus the function after the run, into one function. At run time an indirect call to
one of them dies with "Call to invalid or unregistered function".

This lists every such thunk that is not a function start in codegen.partition.json, and the address right
after each run (the function it was glued to), as a TOML block for app/thunks.toml.

Usage:
    python tools/thunks.py --image out/sh3_image.bin --gen app/generated/sh3 --toml app/thunks.toml
"""
import argparse
import json
import os
import struct

BASE = 0x82000000


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--image", default="out/sh3_image.bin")
    p.add_argument("--gen", default="app/generated/sh3")
    p.add_argument("--toml", default="app/thunks.toml")
    p.add_argument("--code", default="0x820A0000-0x823E70FC", help="code range of the image (from the log)")
    a = p.parse_args()

    img = open(a.image, "rb").read()
    lo, hi = (int(x, 16) for x in a.code.split("-"))
    starts = {int(k, 16) for k in json.load(open(os.path.join(a.gen, "codegen.partition.json")))["assignments"]}

    def word(addr):
        return struct.unpack_from(">I", img, addr - BASE)[0]

    def is_thunk(addr):
        w0, w1 = word(addr), word(addr + 4)
        # addi r3,r3,imm (opcode 14, rD=3, rA=3), then b (opcode 18, AA=0, LK=0)
        return (w0 >> 16) == 0x3863 and (w1 >> 26) == 18 and (w1 & 3) == 0

    found = []
    addr = lo
    while addr < hi - 8:
        if is_thunk(addr):
            run = addr
            while addr < hi - 8 and is_thunk(addr):
                if addr not in starts:
                    found.append((addr, "thunk"))
                addr += 8
            # The code right after a run that starts inside a function was glued to it.
            if addr not in starts and run not in starts and word(addr) != 0:
                found.append((addr, "after a thunk run at 0x%08X" % run))
            elif addr not in starts and word(addr) != 0 and any(t[0] == run + 8 for t in found):
                found.append((addr, "after a thunk run at 0x%08X" % run))
            continue
        addr += 4

    with open(a.toml, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/thunks.py: \"this\" adjusting thunks (addi r3,r3,-N; b) and the functions\n")
        f.write("# glued after their runs, which the analysis did not mark as function starts.\n")
        f.write("[functions]\n")
        for addr, why in found:
            size = " size = 8 " if why == "thunk" else " "
            f.write('"0x%08X" = {%s}   # %s\n' % (addr, size, why))
    print("%d thunks, %d glued functions -> %s" % (sum(1 for t in found if t[1] == "thunk"),
                                                  sum(1 for t in found if t[1] != "thunk"), a.toml))


if __name__ == "__main__":
    main()
